public class MyAssignments {
	public static void main(String[] args) {
		
		int  assignments = 3;
		
		while (assignments > 0) {
				System.out.println("I finished one assignment.");
				assignments--;
				System.out.println("Assignments left: " + assignments);
		}
		
		System.out.println("All assignments are done!");				
	}
}